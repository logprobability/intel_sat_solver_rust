// The solver mode, as in /topor_tool/solver_mode: 0 -- 32-bit index, uncompressed, 1 -- 64-bit index, uncompressed, 2 -- 64-bit index, bit-array compression
pub fn NewFuzzSolver(solverMode: u8, varsNumHint: TLit) -> Box<dyn TFuzzSolver>
{
	match solverMode
	{
		0 => Box::new(CTopor::<u32, false>::new(varsNumHint)),
		1 => Box::new(CTopor::<u64, false>::new(varsNumHint)),
		_ => Box::new(CTopor::<u64, true>::new(varsNumHint)),
	}
}

// A DRAT sink, which is shared between the solver and the harness
#[derive(Clone, Default)]
pub struct CSharedSink
{
	pub m_Buf: Rc<RefCell<Vec<u8>>>,
	// Fail every write after the given number of bytes (if any)
	pub m_FailAfter: Option<usize>,
}

impl std::io::Write for CSharedSink
{
	fn write(&mut self, buf: &[u8]) -> std::io::Result<usize>
	{
		if let Some(failAfter) = self.m_FailAfter
		{
			if self.m_Buf.borrow().len() + buf.len() > failAfter
			{
				return Err(std::io::Error::other("the sink is full"));
			}
		}
		self.m_Buf.borrow_mut().extend_from_slice(buf);
		Ok(buf.len())
	}

	fn flush(&mut self) -> std::io::Result<()>
	{
		Ok(())
	}
}

// What the solver answered for one query
#[derive(Clone, Debug, PartialEq)]
pub struct TFuzzOutcome
{
	pub m_Ret: TToporReturnVal,
	// The model, if satisfiable
	pub m_Model: Vec<TToporLitVal>,
	// The assumptions in the unsatisfiable core, if unsatisfiable
	pub m_RequiredAssumps: Vec<bool>,
}

fn CutAt0(c: &[TLit]) -> &[TLit]
{
	match c.iter().position(|l| *l == 0)
	{
		Some(p) => &c[..p],
		None => c,
	}
}

// Runs the scenario on the given solver mode and verifies every answer of the solver; panics on any discrepancy
// failAllocsAfter: make every allocation starting from the given one fail (to test the behavior of the solver in memory-out situations)
pub fn RunScenario(s: &TFuzzScenario, solverMode: u8, failAllocsAfter: Option<u64>) -> Vec<TFuzzOutcome>
{
	let mut oracle = if s.m_Vars <= MaxOracleVars { Some(CFuzzOracle::new(s.m_Vars)) } else { None };
	let mut clss: Vec<Vec<TLit>> = vec![];
	let mut outcomes = vec![];
	let learnts: Rc<RefCell<Vec<Vec<TLit>>>> = Rc::new(RefCell::new(vec![]));
	let drat = CSharedSink::default();

	if let Some(failAllocsAfter) = failAllocsAfter
	{
		alloc_fault::fail_after(failAllocsAfter);
	}

	let mut solver = NewFuzzSolver(solverMode, s.m_VarsNumHint);
	if s.m_Drat != 0
	{
		solver.FDumpDrat(Box::new(drat.clone()), s.m_Drat.is_multiple_of(2), s.m_Drat > 2);
	}
	if s.m_CbLearnt
	{
		let learntsCb = learnts.clone();
		solver.FSetCbNewLearntCls(Some(Box::new(move |c: &[TLit]|
		{
			learntsCb.borrow_mut().push(c.to_vec());
			TStopTopor::VAL_CONTINUE
		})));
	}
	if let Some(stopAfter) = s.m_CbStopAfter
	{
		let mut invs = 0;
		solver.FSetCbStopNow(Some(Box::new(move ||
		{
			invs += 1;
			if invs > stopAfter { TStopTopor::VAL_STOP } else { TStopTopor::VAL_CONTINUE }
		})));
	}
	if s.m_Verbosity != 0
	{
		solver.FSetParam("/verbosity/level", s.m_Verbosity as f64);
	}

	let VerifyLearnts = |oracle: &Option<CFuzzOracle>|
	{
		for c in learnts.borrow_mut().drain(..)
		{
			let oracle = match oracle
			{
				Some(oracle) => oracle,
				None => continue,
			};
			// The empty clause is reported for every unsatisfiable query, including the ones, which are unsatisfiable only under the assumptions
			if c.is_empty()
			{
				continue;
			}
			assert!(oracle.IsImplied(&c), "A clause generated by the solver isn't implied by the formula: {:?}", c);
		}
	};

	for op in &s.m_Ops
	{
		if solver.FIsError()
		{
			break;
		}
		match op
		{
			TFuzzOp::AddClause(c) =>
			{
				solver.FAddClause(c);
				let c = CutAt0(c).to_vec();
				// The solver may generate clauses already when a clause is added (e.g., when literals falsified at level 0 are removed)
				if let Some(oracle) = &mut oracle
				{
					oracle.AddClause(&c);
				}
				clss.push(c);
			}
			TFuzzOp::Solve(assumps, confThr) =>
			{
				let ret = solver.FSolve(assumps, (f64::MAX, true), *confThr);
				let assumps = CutAt0(assumps);
				let mut outcome = TFuzzOutcome { m_Ret: ret, m_Model: vec![], m_RequiredAssumps: vec![] };
				match ret
				{
					TToporReturnVal::RET_SAT =>
					{
						let IsSat = |l: TLit| solver.FGetLitValue(l) == TToporLitVal::VAL_SATISFIED;
						for c in &clss
						{
							// A variable, which appears only in tautologies, is unknown to the solver
							let isTau = c.iter().any(|l| c.contains(&-*l));
							assert!(isTau || c.iter().any(|l| IsSat(*l)), "The model doesn't satisfy the clause {:?}", c);
						}
						for a in assumps
						{
							assert!(IsSat(*a), "The model doesn't satisfy the assumption {}", a);
						}
						outcome.m_Model = solver.FGetModel();
						for (v, val) in outcome.m_Model.iter().enumerate().skip(1)
						{
							assert_eq!(*val, solver.FGetLitValue(v as TLit));
						}
					}
					TToporReturnVal::RET_UNSAT =>
					{
						assert!(oracle.as_ref().is_none_or(|o| !o.IsSatUnder(assumps)), "The solver returned UNSAT for a satisfiable query; assumptions: {:?}", assumps);
						if !solver.FIsError()
						{
							outcome.m_RequiredAssumps = (0..assumps.len()).map(|i| solver.FIsAssumptionRequired(i)).collect();
							if !solver.FIsError()
							{
								let core: Vec<TLit> = assumps.iter().zip(&outcome.m_RequiredAssumps).filter(|(_, r)| **r).map(|(a, _)| *a).collect();
								assert!(oracle.as_ref().is_none_or(|o| !o.IsSatUnder(&core)), "The formula is satisfiable under the reported core {:?} of {:?}", core, assumps);
							}
						}
					}
					TToporReturnVal::RET_CONFLICT_OUT => assert!(*confThr != u64::MAX),
					TToporReturnVal::RET_USER_INTERRUPT if failAllocsAfter.is_some() => (),
					TToporReturnVal::RET_USER_INTERRUPT => assert!(s.m_CbStopAfter.is_some()),
					TToporReturnVal::RET_MEM_OUT => assert!(failAllocsAfter.is_some(), "Unexpected memory-out: {}", solver.FGetStatusExplanation()),
					// A parameter combination, which the solver rejects, is not a bug
					TToporReturnVal::RET_PARAM_ERROR => (),
					_ => panic!("Unexpected return value {} : {}", ret, solver.FGetStatusExplanation()),
				}
				outcomes.push(outcome);
			}
			TFuzzOp::SetParam(name, val) => solver.FSetParam(name, *val),
			TFuzzOp::FixPolarity(l, onlyOnce) => solver.FFixPolarity(*l, *onlyOnce),
			TFuzzOp::BoostScore(v, mult) => solver.FBoostScore(*v, *mult),
			TFuzzOp::ClearUserPolarityInfo(v) => solver.FClearUserPolarityInfo(*v),
			TFuzzOp::CreateInternalLit(l) => solver.FCreateInternalLit(*l),
			TFuzzOp::Backtrack(toZero) =>
			{
				// Backtrack to level 0 or to the level of some assigned variable
				let mut decLevel = 0;
				if !*toZero
				{
					for v in 1..=s.m_Vars as TLit
					{
						if solver.FGetLitValue(v) == TToporLitVal::VAL_SATISFIED || solver.FGetLitValue(v) == TToporLitVal::VAL_UNSATISFIED
						{
							decLevel = decLevel.max(solver.FGetLitDecLevel(v));
						}
					}
					decLevel /= 2;
				}
				solver.FBacktrack(decLevel);
			}
			TFuzzOp::ChangeConfigToGiven(configNum) =>
			{
				let _ = solver.FChangeConfigToGiven(*configNum);
			}
			TFuzzOp::Stats =>
			{
				assert!(solver.FStats().contains("c ToporStt "));
			}
		}
		VerifyLearnts(&oracle);
	}

	if solver.FIsError()
	{
		assert!(!solver.FGetStatusExplanation().is_empty());
		// The scenarios consist of legal API invocations only, so the solver may get into an erroneous state only because of a (deliberate) memory-out
		assert!(failAllocsAfter.is_some(), "The solver unexpectedly moved to an erroneous state: {}", solver.FGetStatusExplanation());
	}
	drop(solver);
	alloc_fault::never_fail();
	outcomes
}

// The entry point of the fuzzers: runs the scenario, encoded by data, on all the solver modes
// The modes differ in how the clauses and the watches are laid out (hence, in the order they are visited), so the models may legitimately differ,
// but the verdicts must be the same (unless the solver was stopped prematurely)
pub fn FuzzOne(data: &[u8], isBig: bool)
{
	let s = GenScenario(data, isBig);
	let o0 = RunScenario(&s, 0, None);
	for solverMode in 1..=2
	{
		let o = RunScenario(&s, solverMode, None);
		assert_eq!(o0.len(), o.len());
		for (r0, r) in o0.iter().zip(&o)
		{
			let IsVerdict = |r: TToporReturnVal| r == TToporReturnVal::RET_SAT || r == TToporReturnVal::RET_UNSAT;
			assert!(!IsVerdict(r0.m_Ret) || !IsVerdict(r.m_Ret) || r0.m_Ret == r.m_Ret, "The solver modes 0 and {} disagree: {} vs. {}", solverMode, r0.m_Ret, r.m_Ret);
		}
	}
}
