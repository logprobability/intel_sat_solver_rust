// The fuzzing harness: turns an arbitrary byte string into an incremental scenario over the public API of the solver
// (clauses, incremental Solve invocations under assumptions, parameter changes, polarity/score manipulations, callbacks, DRAT generation, ...),
// runs it and verifies whatever the solver reports against an exact oracle.
// The harness is the Rust counterpart of scripts/fuzz_and_verify.csh:
// - every model is verified against all the clauses and the assumptions (DiMoCheck's role);
// - every UNSAT answer and every unsatisfiable core is verified against the truth table of the formula;
// - every clause generated by the solver (reported through the new-learnt-clause callback) is verified to be implied by the formula (drat-trim's role).
// The harness is used by the in-crate fuzz tests (tests/fuzz.rs) and by the cargo-fuzz target (fuzz/fuzz_targets/api.rs).

use crate::topor::*;
use crate::topor_dyn_array::alloc_fault;
use std::cell::RefCell;
use std::rc::Rc;
use std::sync::OnceLock;

// The scenarios are small enough for an exact oracle: the set of the models of the formula is held as a bit-set over all the 2^n assignments
pub const MaxOracleVars: usize = 12;

// The byte-string reader: the fuzzer's input is consumed byte by byte; once the input is exhausted, zeros are returned
pub struct CFuzzInput<'a>
{
	m_Data: &'a [u8],
	m_Pos: usize,
}

impl<'a> CFuzzInput<'a>
{
	pub fn new(data: &'a [u8]) -> Self
	{
		CFuzzInput { m_Data: data, m_Pos: 0 }
	}

	pub fn Exhausted(&self) -> bool
	{
		self.m_Pos >= self.m_Data.len()
	}

	pub fn Byte(&mut self) -> u8
	{
		let b = if self.Exhausted() { 0 } else { self.m_Data[self.m_Pos] };
		self.m_Pos += 1;
		b
	}

	// A number in [0, n)
	pub fn Below(&mut self, n: usize) -> usize
	{
		if n <= 1
		{
			return 0;
		}
		if n <= 256 { self.Byte() as usize % n } else { (((self.Byte() as usize) << 8) | self.Byte() as usize) % n }
	}

	pub fn Chance(&mut self, percent: usize) -> bool
	{
		self.Below(100) < percent
	}
}

// A deterministic pseudo-random byte generator for the in-crate fuzz tests (xorshift64*)
pub fn RandomBytes(seed: u64, len: usize) -> Vec<u8>
{
	let mut x = seed.wrapping_mul(0x9E3779B97F4A7C15) | 1;
	let mut res = Vec::with_capacity(len);
	while res.len() < len
	{
		x ^= x >> 12;
		x ^= x << 25;
		x ^= x >> 27;
		res.extend_from_slice(&x.wrapping_mul(0x2545F4914F6CDD1D).to_le_bytes());
	}
	res.truncate(len);
	res
}

// A parameter of the solver library, as parsed from its description
#[derive(Clone, Debug)]
pub struct TFuzzParam
{
	pub m_Name: String,
	pub m_Vals: Vec<f64>,
}

fn ParseLimit(s: &str, typeName: &str) -> f64
{
	match s
	{
		"min(d)" => f64::MIN_POSITIVE,
		"max(d)" => f64::MAX,
		"lowest(d)" => f64::MIN,
		"epsilon(d)" => f64::EPSILON,
		"min(f)" => f32::MIN_POSITIVE as f64,
		"max(f)" => f32::MAX as f64,
		"lowest(f)" => f32::MIN as f64,
		"epsilon(f)" => f32::EPSILON as f64,
		_ => s.parse::<f64>().unwrap_or_else(|_| panic!("cannot parse the limit {} of type {}", s, typeName)),
	}
}

// The parameters, which the generic fuzzing doesn't touch
fn IsParamExcluded(name: &str) -> bool
{
	// Verbosity is controlled by the scenario header; a global timeout makes the solver permanently unusable; the debug-model parameters print or exit;
	// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): if the restart strategies of the different query types are not the same,
	// RestartInit may clear an LBD window, which has never been initialized, that is, memset an empty array, which is asserted against
	// (e.g.: r /mode/value 6; r /__s/restarts/lbd/blocking/enable 1; r /restarts/strategy_s 0; s 0; oc 54; s -4 5 3 -7 0).
	// So the restart strategies are changed only through the mode, which sets all of them to the same value
	name.starts_with("/restarts/strategy_") ||
	name.starts_with("/verbosity/") || name.starts_with("/timeout/") || name == "/debugging/print_debug_model_invocation" || name == "/debugging/verify_debug_model_invocation" ||
	// The parameters of the Rust-only extensions: the scenarios are functions of the list of the parameters (a parameter is drawn by its index), and the ones
	// which were found by a search over the seeds (cov_core.rs) reach their rarely visited code only with the list they were found with.
	// (The hints have no effect without HintPhase/HintScore, which the scenarios don't invoke; tests/ext_hints.rs fuzzes them.)
	name == "/phase/hints/on" || name == "/decision/score_hints/mult" ||
	// (tests/ext_target_phase.rs fuzzes these)
	name.starts_with("/phase/target/") || name.starts_with("/phase/rephase/")
}

// Parses the description of the parameters, which is provided by the solver, into the list of the parameters with a few interesting legal values for each
pub fn FuzzParams() -> &'static Vec<TFuzzParam>
{
	static PARAMS: OnceLock<Vec<TFuzzParam>> = OnceLock::new();
	PARAMS.get_or_init(||
	{
		let descr = CTopor::<u32, false>::new(1).GetParamsDescr();
		let mut res = vec![];
		for line in descr.lines()
		{
			// c <name> : <type>; default = <default> in [<min>, <max>] : <description> (with color codes around the name and the default part)
			let line: String = line.replace("\x1b[1;35m", "").replace("\x1b[1;32m", "").replace("\x1b[0m", "");
			if !line.starts_with("c /")
			{
				continue;
			}
			let (name, rest) = line[2..].split_once(" : ").unwrap();
			if IsParamExcluded(name)
			{
				continue;
			}
			let (typeName, rest) = rest.split_once("; default = ").unwrap();
			let (defaultStr, rest) = rest.split_once(" in [").unwrap();
			let (limits, _) = rest.split_once("] : ").unwrap();
			let (loStr, hiStr) = limits.split_once(", ").unwrap();
			let (lo, hi) = (ParseLimit(loStr, typeName), ParseLimit(hiStr, typeName));
			let defaults: Vec<f64> = defaultStr.trim_matches(|c| c == '{' || c == '}').split(", ").map(|s| ParseLimit(s, typeName)).collect();
			let isFloat = typeName == "d" || typeName == "f";
			let mut cands: Vec<f64> = defaults.clone();
			if isFloat
			{
				for d in &defaults
				{
					cands.extend_from_slice(&[d * 0.5, d * 1.5]);
				}
				cands.extend_from_slice(&[0., 0.01, 0.3, 0.5, 0.9, 1., 1.3, 2., 5.]);
				cands.retain(|c| *c >= lo && *c <= hi && *c >= -100. && *c <= 100.);
			}
			else
			{
				cands.extend_from_slice(&[lo, lo + 1., lo + 2., lo + 3., 4., 5., 7., 10., 20., 50., hi]);
				for d in &defaults
				{
					cands.extend_from_slice(&[(d / 2.).floor(), d + 1.]);
				}
				cands.retain(|c| *c >= lo && *c <= hi);
			}
			// Clause deletion with no learnt clauses allowed at all is an (expected) allocation failure: see ClsDeletionInit
			if name == "/deletion/clause/trigger_init"
			{
				cands.retain(|c| *c != 0.);
			}
			// The deleted chunks of the watch buffer are marked by the binary logarithm of their size, so the number of entries must be a power of 2 (asserted by the solver)
			if name == "/bcp/init_entries_per_wl"
			{
				// The minimum depends on the width of the index; 4 is legal for every solver mode
				cands.retain(|c| (*c as u64).is_power_of_two() && *c >= 4.);
			}
			// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): with the heavy consistency checks on, the best-score-per-decision-level
			// assertion of Assign fails when a clause is added after an UNSAT-core query (e.g.: s 2 0; 6 -5 -5 2 0; s 0; -2 -6 1 3 0; s -2 2 -3 0 + ucore; -2 -1 0)
			// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): a glue of 0 gets enqueued to the LBD window, which asserts non-zero values
			// (e.g.: r /mode/value 5; r /restarts/lbd/thr_glue_val 0; 2 -4 0; -4 -3 1 -2 0; s 3 -1 4 0)
			if name == "/restarts/lbd/thr_glue_val"
			{
				cands.retain(|c| *c > 0.);
			}
			// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): the best-score-of-level-0 assertion of SimplifyIfRequired fails
			// (e.g.: r /__s/deletion/simplify_global_level_strat 2; s 0; s 0; -9 -9 0; -7 11 0; -7 -7 0; oc 110; s 0)
			if name == "/deletion/simplify_global_level_strat"
			{
				cands.retain(|c| *c == 0.);
			}
			// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): when the assumptions are ignored in the glue, their decision levels aren't marked,
			// which fails an assertion of the clause minimization (e.g.: r /assumptions/ignore_in_glue 1; -1 -7 0; 2 -1 5 6 0; -3 -2 0; 5 1 0; 3 -4 -2 0; 4 -3 7 2 0; 2 -7 4 5 0; s 0; 6 2 4 -5 0; s -4 -6 0)
			if name == "/assumptions/ignore_in_glue"
			{
				cands.retain(|c| *c == 0.);
			}
			// The minimum is 1 + epsilon, which is printed as 1.000000
			if name == "/restarts/luby/conflict_increment"
			{
				cands.retain(|c| *c > 1.);
			}
			if name == "/debugging/assert_consistency"
			{
				// The same holds for the best-score assertion of UpdateScoreVar, which is on already at level 1
				// (e.g.: r /debugging/assert_consistency 1; oc 2; s 0; -5 -2 -1 0; -2 4 0; -2 -8 -5 0; s 0; oc 9; s -4 4 3 -7 0 + ucore; 4 -2 -6 8 0)
				cands.retain(|c| *c < 1.);
			}
			cands.sort_by(|a, b| a.partial_cmp(b).unwrap());
			cands.dedup();
			assert!(!cands.is_empty(), "{}", name);
			res.push(TFuzzParam { m_Name: name.to_string(), m_Vals: cands });
		}
		res
	})
}

#[derive(Clone, Debug)]
pub enum TFuzzOp
{
	AddClause(Vec<TLit>),
	Solve(Vec<TLit>, u64),
	SetParam(String, f64),
	FixPolarity(TLit, bool),
	BoostScore(TLit, f64),
	ClearUserPolarityInfo(TLit),
	CreateInternalLit(TLit),
	Backtrack(bool),
	ChangeConfigToGiven(u16),
	Stats,
}

#[derive(Clone, Debug, Default)]
pub struct TFuzzScenario
{
	pub m_Vars: usize,
	pub m_VarsNumHint: TLit,
	// 0: no DRAT; 1: text; 2: binary; +2: sort every clause
	pub m_Drat: u8,
	pub m_CbLearnt: bool,
	// The stop-now callback requests to stop after the given number of invocations (if any)
	pub m_CbStopAfter: Option<u32>,
	pub m_Verbosity: u8,
	pub m_Ops: Vec<TFuzzOp>,
}

fn GenLit(inp: &mut CFuzzInput, vars: usize) -> TLit
{
	let v = 1 + inp.Below(vars) as TLit;
	if inp.Byte() & 1 == 0 { v } else { -v }
}

// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): m_RstNumericLocalConfsSinceRestartAtDecLevelCreation is resized by Solve only
// if one of the restart strategies is numeric. If the strategies are changed to non-numeric between two queries and new variables are added,
// the array stays too short, and NewDecLevel writes beyond its capacity. So the restart strategies (which the mode determines too) are set only before the first query.
fn IsParamOnlyBeforeFirstQuery(name: &str) -> bool
{
	// Another upstream issue of the same kind as with Backtrack (see below): turning /add_user_clause/guarantee_level_0 on in the middle makes the next query
	// backtrack to level 0 with literals still to be propagated (e.g.: s 4 -9 2 -12 11 0; 12 -4 8 0; r /add_user_clause/guarantee_level_0 1; s 0)
	name.starts_with("/restarts/strategy_") || name == "/mode/value" || name == "/add_user_clause/guarantee_level_0"
		// Raising the postponement after inprocessing has already been invoked fails an assertion of InprocessIfRequired
		// (e.g.: r /inprocessing/on 1; -5 8 0; s 0; r /inprocessing/postpone_first_inv_conflicts 3; -7 9 0; s 0)
		|| name == "/inprocessing/postpone_first_inv_conflicts"
}

fn GenParam(inp: &mut CFuzzInput, isBeforeFirstQuery: bool) -> TFuzzOp
{
	let params = FuzzParams();
	let mut pInd = inp.Below(params.len());
	while !isBeforeFirstQuery && IsParamOnlyBeforeFirstQuery(&params[pInd].m_Name)
	{
		pInd = (pInd + 1) % params.len();
	}
	let p = &params[pInd];
	let val = p.m_Vals[inp.Below(p.m_Vals.len())];
	// The context prefixes: apply after the initial invocation / for the lifetime of a short invocation
	let name = match if IsParamOnlyBeforeFirstQuery(&p.m_Name) { 2 } else { inp.Below(12) }
	{
		0 => "/__ai".to_string() + &p.m_Name,
		1 => "/__s".to_string() + &p.m_Name,
		_ => p.m_Name.clone(),
	};
	TFuzzOp::SetParam(name, val)
}

// Generates a scenario out of the fuzzer's input
// isBig: generate a scenario over (many) more variables than the exact oracle can handle; the scenario is then long enough to reach
// restarts, clause deletion, simplification and buffer compression; the answers are verified by checking the models and by comparing the verdicts of the solver modes
pub fn GenScenario(data: &[u8], isBig: bool) -> TFuzzScenario
{
	let mut inp = CFuzzInput::new(data);
	let mut s = TFuzzScenario::default();
	s.m_Vars = if isBig { 20 + inp.Below(130) } else { 1 + inp.Below(MaxOracleVars) };
	s.m_VarsNumHint = match inp.Below(4)
	{
		0 => 0,
		1 => s.m_Vars as TLit,
		2 => 1,
		_ => 2 * s.m_Vars as TLit,
	};
	s.m_Drat = if inp.Chance(30) { 1 + inp.Below(4) as u8 } else { 0 };
	s.m_CbLearnt = inp.Chance(70);
	s.m_CbStopAfter = if inp.Chance(8) { Some(inp.Below(40) as u32) } else { None };
	s.m_Verbosity = if !isBig && inp.Chance(4) { 1 + inp.Below(3) as u8 } else { 0 };

	// The initial parameters
	let initParams = if inp.Chance(75) { inp.Below(8) } else { 0 };
	if inp.Chance(50)
	{
		s.m_Ops.push(TFuzzOp::SetParam("/mode/value".to_string(), inp.Below(9) as f64));
	}
	for _ in 0..initParams
	{
		s.m_Ops.push(GenParam(&mut inp, true));
	}

	// The clause length profile and density of this scenario
	let maxLen = 2 + inp.Below(7);
	let longClsBias = inp.Chance(50);
	// A big scenario is around the satisfiability threshold of random 3-SAT, where the queries are the hardest
	let opsNum = if isBig { s.m_Vars * (3 + inp.Below(4)) } else { 1 + inp.Below(if s.m_Verbosity > 1 { 40 } else { 250 }) };
	let mut isBeforeFirstQuery = true;
	// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): backtracking through the API when a clause has been added since the latest query
	// may leave an unassigned literal to propagate, which fails an assertion in BCP (e.g.: s -1 -3 0; 3 -4 0; b 0; s 0). So we backtrack only right after a query.
	let mut canBacktrack = false;
	for _ in 0..opsNum
	{
		if inp.Exhausted()
		{
			break;
		}
		// Many more clauses than queries in a big scenario
		let opKind = if isBig && inp.Chance(90) { 0 } else { inp.Below(100) };
		let canBacktrackNow = canBacktrack;
		canBacktrack = (75..=84).contains(&opKind) || (canBacktrack && (96..=97).contains(&opKind));
		let op = match opKind
		{
			0..=74 =>
			{
				// No empty clauses and almost no short clauses in a big scenario: otherwise it would be decided too easily
				let len = match if isBig { 6 + inp.Below(200) } else { inp.Below(20) }
				{
					0 => 0,
					1 => 1,
					2..=5 => 2,
					6 => 2,
					_ if isBig => if inp.Chance(90) { 3 } else { 3 + inp.Below(maxLen) },
					_ => if longClsBias { 3 + inp.Below(maxLen) } else { 2 + inp.Below(3) },
				};
				let mut c: Vec<TLit> = (0..len).map(|_| GenLit(&mut inp, s.m_Vars)).collect();
				// An end-of-clause mark, which doesn't have to be the last entry
				match inp.Below(16)
				{
					0 => c.push(0),
					1 if !c.is_empty() =>
					{
						let pos = inp.Below(c.len());
						c.insert(pos, 0)
					}
					_ => (),
				}
				TFuzzOp::AddClause(c)
			}
			75..=84 =>
			{
				let assumpsNum = if inp.Chance(60) { inp.Below(1 + s.m_Vars.min(6)) } else { 0 };
				let mut assumps: Vec<TLit> = (0..assumpsNum).map(|_| GenLit(&mut inp, s.m_Vars)).collect();
				if inp.Chance(10)
				{
					assumps.push(0);
				}
				let confThr = match inp.Below(10)
				{
					0 => inp.Below(4) as u64,
					1 => 1 + inp.Below(200) as u64,
					// Bound the run-time of the big scenarios
					_ => if isBig { 20000 } else { u64::MAX },
				};
				isBeforeFirstQuery = false;
				TFuzzOp::Solve(assumps, confThr)
			}
			85..=89 => GenParam(&mut inp, isBeforeFirstQuery),
			90..=95 =>
			{
				// Upstream issue (reproduced faithfully by the fork, hence avoided by the fuzzer): the functions, which may create a new internal variable
				// (CreateInternalLit, BoostScore, FixPolarity, ClearUserPolarityInfo), don't reserve its watches, which are reserved only by the next Solve;
				// compressing the watch buffer in between (when adding a clause) visits the watches of every existing literal, that is, reads beyond the allocated watches
				// (e.g.: -1 -1 0; -4 1 3 5 0; s 0; -1 3 -4 0; lb 2 1e50; -4 -4 -5 3 0). So the next query immediately follows.
				s.m_Ops.push(match opKind
				{
					90..=91 => TFuzzOp::FixPolarity(GenLit(&mut inp, s.m_Vars), inp.Chance(50)),
					92..=93 => TFuzzOp::BoostScore(1 + inp.Below(s.m_Vars) as TLit, [0.5, 1., 10., 1e50][inp.Below(4)]),
					94 => TFuzzOp::ClearUserPolarityInfo(1 + inp.Below(s.m_Vars) as TLit),
					_ => TFuzzOp::CreateInternalLit(GenLit(&mut inp, s.m_Vars + 2)),
				});
				isBeforeFirstQuery = false;
				canBacktrack = true;
				TFuzzOp::Solve(vec![], u64::MAX)
			}
			96..=97 if canBacktrackNow => TFuzzOp::Backtrack(inp.Chance(50)),
			98 if isBeforeFirstQuery => TFuzzOp::ChangeConfigToGiven(inp.Below(300) as u16),
			_ => TFuzzOp::Stats,
		};
		s.m_Ops.push(op);
	}
	// Always finish with a query
	s.m_Ops.push(TFuzzOp::Solve(vec![], if isBig { 20000 } else { u64::MAX }));
	s
}

// The scenario in the incremental DIMACS format of the solver executable (see Main.cc/main.rs), e.g., for reproducing an issue with the C++ solver
// A backtracking to a level other than 0 depends on the run-time state, so it's emitted as a comment
pub fn ScenarioToCnf(s: &TFuzzScenario) -> String
{
	let Lits = |c: &[TLit]| c.iter().take_while(|l| **l != 0).map(|l| l.to_string() + " ").collect::<String>() + "0\n";
	let mut res = format!("p cnf {} 0\n", s.m_VarsNumHint);
	if s.m_Verbosity != 0
	{
		res += &format!("r /verbosity/level {}\n", s.m_Verbosity);
	}
	for op in &s.m_Ops
	{
		res += &match op
		{
			TFuzzOp::AddClause(c) => Lits(c),
			TFuzzOp::Solve(assumps, confThr) => (if *confThr != u64::MAX { format!("oc {}\n", confThr) } else { String::new() }) + "s " + &Lits(assumps),
			TFuzzOp::SetParam(name, val) => format!("r {} {}\n", name, val),
			TFuzzOp::FixPolarity(l, onlyOnce) => format!("lf {} {}\n", l, *onlyOnce as u8),
			TFuzzOp::BoostScore(v, mult) => format!("lb {} {}\n", v, mult),
			TFuzzOp::ClearUserPolarityInfo(v) => format!("lc {}\n", v),
			TFuzzOp::CreateInternalLit(l) => format!("ll {}\n", l),
			TFuzzOp::Backtrack(toZero) => if *toZero { "b 0\n".to_string() } else { "c b <half of the highest decision level>\n".to_string() },
			TFuzzOp::ChangeConfigToGiven(configNum) => format!("n {}\n", configNum),
			TFuzzOp::Stats => String::new(),
		};
	}
	res
}

// The exact oracle: the set of the models of the formula as a bit-set over all the assignments (bit i of the assignment a is the value of the variable i+1)
#[derive(Clone)]
pub struct CFuzzOracle
{
	m_Vars: usize,
	m_Models: Vec<u64>,
}

impl CFuzzOracle
{
	pub fn new(vars: usize) -> Self
	{
		let bits = 1usize << vars;
		let mut models = vec![u64::MAX; bits.div_ceil(64)];
		if bits < 64
		{
			models[0] = (1u64 << bits) - 1;
		}
		CFuzzOracle { m_Vars: vars, m_Models: models }
	}

	// The set of the assignments, satisfying the literal
	fn LitSet(&self, l: TLit) -> Vec<u64>
	{
		let v = l.unsigned_abs() as usize - 1;
		assert!(v < self.m_Vars);
		(0..self.m_Models.len()).map(|w|
		{
			let pos: u64 = if v < 6
			{
				[0xAAAAAAAAAAAAAAAAu64, 0xCCCCCCCCCCCCCCCC, 0xF0F0F0F0F0F0F0F0, 0xFF00FF00FF00FF00, 0xFFFF0000FFFF0000, 0xFFFFFFFF00000000][v]
			}
			else if (w >> (v - 6)) & 1 == 1
			{
				u64::MAX
			}
			else
			{
				0
			};
			if l > 0 { pos } else { !pos }
		}).collect()
	}

	// The set of the assignments, satisfying the clause
	fn ClsSet(&self, c: &[TLit]) -> Vec<u64>
	{
		let mut res = vec![0u64; self.m_Models.len()];
		for l in c
		{
			for (r, s) in res.iter_mut().zip(self.LitSet(*l))
			{
				*r |= s;
			}
		}
		res
	}

	pub fn AddClause(&mut self, c: &[TLit])
	{
		let clsSet = self.ClsSet(c);
		for (m, s) in self.m_Models.iter_mut().zip(clsSet)
		{
			*m &= s;
		}
	}

	pub fn IsSatUnder(&self, assumps: &[TLit]) -> bool
	{
		let mut models = self.m_Models.clone();
		for a in assumps
		{
			for (m, s) in models.iter_mut().zip(self.LitSet(*a))
			{
				*m &= s;
			}
		}
		models.iter().any(|m| *m != 0)
	}

	// Is the clause implied by the formula?
	pub fn IsImplied(&self, c: &[TLit]) -> bool
	{
		let clsSet = self.ClsSet(c);
		self.m_Models.iter().zip(clsSet).all(|(m, s)| m & !s == 0)
	}
}

