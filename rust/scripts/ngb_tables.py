#!/usr/bin/env python3
# NGBoost experiment, step 6: the cost of the advice relative to solving, and the assembly of the tables of the other steps into one file.
#
# Usage: ngb_tables.py --work DIR [--out FILE.md]
#   Reads DIR/instances.json, DIR/phase_metrics.json and DIR/tables/[1-4]_*.md; writes DIR/tables/5_cost.md and FILE.md (docs/search_quality/ngboost_tables.md by default).
import argparse, glob, json, os, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np

def main():
	here = os.path.dirname(os.path.abspath(__file__))
	ap = argparse.ArgumentParser()
	ap.add_argument("--work", required=True)
	ap.add_argument("--out", default=os.path.join(here, "..", "docs", "search_quality", "ngboost_tables.md"))
	a = ap.parse_args()
	records = json.load(open(os.path.join(a.work, "instances.json")))
	times = json.load(open(os.path.join(a.work, "phase_metrics.json")))["times"]
	perVar = {m: t[1] / max(t[3], 1) for m, t in times.items()}
	md = ["## 5. The cost of the advice relative to solving", "",
		"Generated by `scripts/ngb_tables.py`. `parse`: reading the CNF in Python; `features`: `ngb_common.features` (numpy; a few linear passes over the literal occurrences); `inference`: the predictor's time for the variables of the instance",
		"(the per-variable times of section 1); `solve`: the CPU time of the baseline solver process, which includes its own reading of the file. Medians over the instances of the group.",
		"`advice/solve`: (features + ngb inference) / solve, the median over the instances; `advice > solve`: the share of the instances on which that advice alone takes longer than solving. Parsing is left out of the advice, since the solver has the clauses in memory anyway;",
		"a native implementation of the features would be much faster than this numpy one, and the training (minutes, offline) is not counted.", "",
		"| group | instances | variables | clauses | conflicts | parse ms | features ms | inference ms: ngb | gbm | logreg | solve ms | advice/solve | advice > solve |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
	groups = []
	for fam in ("rand", "factor", "col"):
		for status in ("SAT", "UNSAT"):
			groups.append((f"{fam}, {status}, >= 200 conflicts", [r for r in records if r["family"] == fam and r["status"] == status and r["confs"] >= 200 and "feature_s" in r]))
	groups.append(("generated, < 200 conflicts", [r for r in records if r["family"] != "planner" and r["confs"] < 200 and "feature_s" in r]))
	groups.append(("planner, single query (.plain)", [r for r in records if r["family"] == "planner" and "feature_s" in r]))
	med = lambda xs: float(np.median(xs))
	for title, rs in groups:
		if not rs:
			continue
		advice = [(r["feature_s"] + perVar["ngb"] * r["vars"]) / max(r["cpu"], 1e-4) for r in rs]
		md.append(f"| {title} | {len(rs)} | {med([r['vars'] for r in rs]):.0f} | {med([r['clauses'] for r in rs]):.0f} | {med([r['confs'] for r in rs]):.0f} | {med([r['parse_s'] for r in rs]) * 1e3:.2f} | {med([r['feature_s'] for r in rs]) * 1e3:.2f} | "
			+ " | ".join(f"{med([perVar[m] * r['vars'] for r in rs]) * 1e3:.2f}" for m in ("ngb", "gbm", "logreg")) + f" | {med([r['cpu'] for r in rs]) * 1e3:.1f} | {med(advice):.3f} | {np.mean([x > 1 for x in advice]):.2f} |")
	md += ["", "Training time and inference time per variable of each predictor are in the last table of section 1."]
	with open(os.path.join(a.work, "tables", "5_cost.md"), "w") as f:
		f.write("\n".join(md) + "\n")
	parts = ["# NGBoost for the solver: the tables", "", "Generated by `scripts/ngb_data.py`, `ngb_phase.py`, `ngb_backbone.py`, `ngb_solve.py`, `ngb_regress.py` and assembled by `ngb_tables.py`; see [`ngboost.md`](ngboost.md) for the reading and the commands.", ""]
	for p in sorted(glob.glob(os.path.join(a.work, "tables", "[1-5]_*.md"))):
		parts.append(open(p).read())
	with open(a.out, "w") as f:
		f.write("\n".join(parts))
	print("\n".join(md))

if __name__ == "__main__":
	main()
