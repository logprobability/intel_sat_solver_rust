#!/usr/bin/env python3
# NGBoost experiment, step 3: how ambiguous is the label? A satisfiable formula has many models, and the label of a variable is its value in ONE of them.
# A variable is a backbone variable, if it takes the same value in every model; only for those is the label a fact about the formula.
#
# * Random 3-SAT (the satisfiable instances with at most --max-vars variables): every variable is tested by solving the formula with the unit clause of the opposite literal;
#   unsatisfiable means backbone.
# * Factoring of a semiprime p*q, p != q: the formula has exactly two models (the factors in either order; the rest of the multiplier is determined by them), so the backbone
#   is the set of the variables on which the two agree; the second model is obtained by one more run with a bit, on which the factors differ, forced the other way.
# * 3-colouring: no solver call is needed: any permutation of the colours maps a model to a model, so no variable is a backbone variable.
#
# Usage: ngb_backbone.py --exe PATH --work DIR [--max-vars N] [--max-instances N] [--timeout SEC] [--jobs N]
#   Reads vars.npz, instances.json, preds.npz and the base hints; writes DIR/backbone.npz and DIR/tables/2_backbone.md.
import argparse, json, os, sys
from concurrent.futures import ThreadPoolExecutor

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from search_quality_bench import run_one
from ngb_common import VERIFY, read_model, write
from ngb_phase import MODELS, metrics

def with_unit(src, dst, lit):
	lines = [l for l in open(src).read().splitlines() if l and not l.startswith("c")]
	head = lines[0].split()
	assert head[:2] == ["p", "cnf"]
	write(dst, f"p cnf {head[2]} {int(head[3]) + 1}\n" + "\n".join(lines[1:]) + f"\n{lit} 0\n")

def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--exe", required=True)
	ap.add_argument("--work", required=True)
	ap.add_argument("--max-vars", type=int, default=200)
	ap.add_argument("--max-instances", type=int, default=40)
	ap.add_argument("--timeout", type=float, default=60)
	ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) - 2))
	a = ap.parse_args()
	d = np.load(os.path.join(a.work, "vars.npz"))
	y, inst, var = d["y"], d["inst"], d["var"]
	records = json.load(open(os.path.join(a.work, "instances.json")))
	preds = np.load(os.path.join(a.work, "preds.npz"))
	tmp = os.path.join(a.work, "backbone")
	os.makedirs(tmp, exist_ok=True)
	backbone = np.full(len(y), -1)
	sat = [i for i, r in enumerate(records) if r["role"] == "phase" and r["status"] == "SAT"]
	rand = [i for i in sat if records[i]["family"] == "rand" and records[i]["vars"] <= a.max_vars][:a.max_instances]
	jobs = [(i, row) for i in rand for row in np.nonzero(inst == i)[0]]
	def test(job):
		i, row = job
		path = os.path.join(tmp, f"{records[i]['name']}.{var[row]}.cnf")
		with_unit(records[i]["path"], path, -int(var[row]) if y[row] == 1 else int(var[row]))
		res = run_one(a.exe, path, VERIFY, a.timeout)
		os.remove(path)
		return row, res["status"], res["confs"] or 0
	extraConfs = {i: 0 for i in rand}
	undecided = 0
	with ThreadPoolExecutor(max_workers=a.jobs) as ex:
		for (i, _), (row, status, confs) in zip(jobs, ex.map(test, jobs)):
			extraConfs[i] += confs
			if status in ("SAT", "UNSAT"):
				backbone[row] = int(status == "UNSAT")
			else:
				undecided += 1
	print("random 3-SAT done; undecided:", undecided, flush=True)
	# Factoring: the second model
	nFactor = 0
	for i in sat:
		r = records[i]
		if r["family"] != "factor":
			continue
		bits = int(r["name"].split("_b")[1].split("_")[0])
		model = read_model(os.path.join(a.work, "hints", r["name"] + ".base.hints"))
		differ = [k for k in range(1, bits + 1) if model[k] != model[k + bits]]
		if not differ:
			continue
		path, hints = os.path.join(tmp, r["name"] + ".second.cnf"), os.path.join(tmp, r["name"] + ".second.hints")
		with_unit(r["path"], path, -differ[0] if model[differ[0]] else differ[0])
		res = run_one(a.exe, path, VERIFY + ["/topor_tool/write_hints_file", hints], a.timeout)
		if res["status"] != "SAT":
			print("no second model:", r["name"], res["status"])
			continue
		second = read_model(hints)
		# The second model must be the first one with the factors swapped
		assert all(second[k] == model[k + bits] and second[k + bits] == model[k] for k in range(1, bits + 1)), r["name"]
		rows = np.nonzero(inst == i)[0]
		backbone[rows] = [int(second[int(v)] == model[int(v)]) for v in var[rows]]
		nFactor += 1
	np.savez_compressed(os.path.join(a.work, "backbone.npz"), backbone=backbone)

	family = np.array([records[i]["family"] for i in inst])
	md = ["## 2. Label ambiguity: backbone and non-backbone variables", "",
		"Generated by `scripts/ngb_backbone.py`. A backbone variable has the same value in every model, so its label is a fact about the formula; the label of any other variable is the choice of the one model the baseline run found.",
		f"Random 3-SAT: {len(rand)} satisfiable instances of at most {a.max_vars} variables, every variable tested with the opposite unit clause ({len(jobs)} solver runs, {undecided} undecided). "
		f"Factoring: {nFactor} semiprimes, whose two models (the factors in either order; checked) give the backbone. 3-colouring has no backbone variable, by the symmetry of the colours.", "",
		"Predictions: within-family, out-of-sample by instance. `mean conf`: the mean of max(p, 1-p). ECE as in section 1, computed inside the subset.", "",
		"| family | subset | variables | share | model | accuracy | mean conf | Brier | ECE | acc@0.7 (cov) | acc@0.8 (cov) |", "|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|"]
	summary = {}
	for fam in ("rand", "factor"):
		known = (family == fam) & (backbone >= 0) & (y >= 0)
		for name, mask in (("backbone", known & (backbone == 1)), ("non-backbone", known & (backbone == 0)), ("both", known)):
			for model in MODELS[:5]:
				p = preds[f"within:{model}"][mask]
				m = metrics(p, y[mask])
				summary[f"{fam}/{name}/{model}"] = m
				md.append(f"| {fam} | {name} | {int(mask.sum())} | {mask.sum() / max(known.sum(), 1):.3f} | {model} | {m['acc']:.3f} | {np.maximum(p, 1 - p).mean():.3f} | {m['brier']:.4f} | {m['ece']:.4f} | {m['acc0.7']:.3f} ({m['cov0.7']:.2f}) | {m['acc0.8']:.3f} ({m['cov0.8']:.2f}) |")
	shares = [float((backbone[inst == i] == 1).mean()) for i in rand]
	md += ["", f"Backbone share per random 3-SAT instance: minimum {min(shares):.2f}, median {float(np.median(shares)):.2f}, maximum {max(shares):.2f}. "
		f"The cost of the test: {sum(extraConfs.values())} conflicts over the {len(jobs)} runs, against {sum(records[i]['confs'] for i in rand)} for solving the {len(rand)} instances once."]
	with open(os.path.join(a.work, "tables", "2_backbone.md"), "w") as f:
		f.write("\n".join(md) + "\n")
	print("\n".join(md))

if __name__ == "__main__":
	main()
